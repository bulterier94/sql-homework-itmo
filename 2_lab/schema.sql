-- Скрипт пересоздает таблицы, после запуска они очищаются

CREATE EXTENSION IF NOT EXISTS btree_gist;

DROP TABLE IF EXISTS room_amenity CASCADE;
DROP TABLE IF EXISTS user_phone CASCADE;
DROP TABLE IF EXISTS booking CASCADE;
DROP TABLE IF EXISTS amenity CASCADE;
DROP TABLE IF EXISTS room CASCADE;
DROP TABLE IF EXISTS app_user CASCADE;

CREATE TABLE app_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL,
    full_name VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_app_user_email UNIQUE (email),
    CONSTRAINT chk_app_user_email_nonempty CHECK (length(trim(email)) > 0),
    CONSTRAINT chk_app_user_full_name_nonempty CHECK (length(trim(full_name)) > 0)
);

CREATE TABLE room (
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_room_id BIGINT NULL,
    code VARCHAR(40) NOT NULL,
    name VARCHAR(120) NOT NULL,
    capacity INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_room_code UNIQUE (code),
    CONSTRAINT chk_room_capacity_positive CHECK (capacity > 0),
    CONSTRAINT chk_room_code_nonempty CHECK (length(trim(code)) > 0),
    CONSTRAINT fk_room_parent FOREIGN KEY (parent_room_id)
        REFERENCES room(room_id) ON DELETE SET NULL
);

CREATE TABLE amenity (
    amenity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    CONSTRAINT uq_amenity_name UNIQUE (name),
    CONSTRAINT chk_amenity_name_nonempty CHECK (length(trim(name)) > 0)
);

CREATE TABLE booking (
    booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    start_at TIMESTAMPTZ NOT NULL,
    end_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'confirmed',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_booking_room FOREIGN KEY (room_id)
        REFERENCES room(room_id) ON DELETE RESTRICT,
    CONSTRAINT fk_booking_user FOREIGN KEY (user_id)
        REFERENCES app_user(user_id) ON DELETE RESTRICT,
    CONSTRAINT chk_booking_time CHECK (end_at > start_at),
    CONSTRAINT chk_booking_status
        CHECK (status IN ('pending', 'confirmed', 'cancelled', 'completed'))
);

-- Активные брони одной комнаты не пересекаются
ALTER TABLE booking ADD CONSTRAINT ex_booking_no_overlap
    EXCLUDE USING GIST (
        room_id WITH =,
        tstzrange(start_at, end_at, '[)') WITH &&
    )
    WHERE (status IN ('pending', 'confirmed'));

CREATE TABLE room_amenity (
    room_id BIGINT NOT NULL,
    amenity_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT pk_room_amenity PRIMARY KEY (room_id, amenity_id),
    CONSTRAINT fk_room_amenity_room FOREIGN KEY (room_id)
        REFERENCES room(room_id) ON DELETE CASCADE,
    CONSTRAINT fk_room_amenity_amenity FOREIGN KEY (amenity_id)
        REFERENCES amenity(amenity_id) ON DELETE RESTRICT,
    CONSTRAINT chk_room_amenity_quantity CHECK (quantity > 0)
);

-- Слабая сущность, номер телефона идентифицируется парой (user_id, phone).
CREATE TABLE user_phone (
    user_id BIGINT NOT NULL,
    phone VARCHAR(32) NOT NULL,
    label VARCHAR(30) NOT NULL DEFAULT 'personal',
    CONSTRAINT pk_user_phone PRIMARY KEY (user_id, phone),
    CONSTRAINT fk_user_phone_user FOREIGN KEY (user_id)
        REFERENCES app_user(user_id) ON DELETE CASCADE,
    CONSTRAINT chk_user_phone_nonempty CHECK (length(trim(phone)) > 0),
    CONSTRAINT chk_user_phone_label CHECK (label IN ('personal', 'work', 'other'))
);

-- ON DELETE:
-- RESTRICT для booking -> room/user сохраняет историю бронирований
-- CASCADE для room_amenity -> room удаляет зависимые связки удаленной комнаты
-- RESTRICT для room_amenity -> amenity не позволяет удалить используемое удобство
-- CASCADE для user_phone -> app_user удаляет телефоны вместе с пользователем
-- SET NULL для room.parent_room_id сохраняет дочерние помещения при удалении родителя

COMMENT ON TABLE app_user IS 'Пользователи коворкинга';
COMMENT ON COLUMN app_user.email IS 'Email пользователя (альтернативный уникальный ключ)';
COMMENT ON TABLE room IS 'Помещения коворкинга';
COMMENT ON COLUMN room.capacity IS 'Максимальное число человек (положительное значение)';
COMMENT ON TABLE booking IS 'Бронирования помещений с запретом пересечения активных интервалов';
COMMENT ON COLUMN booking.status IS 'Статус (pending, confirmed, cancelled или completed)';
COMMENT ON TABLE room_amenity IS 'Ассоциативная таблица связи помещений и удобств (M:N)';
COMMENT ON TABLE user_phone IS 'Дополнительные телефоны пользователя (зависимая сущность)';
